"""GT (full round-3 GT warm test set) with the R4 extended EASE-lambda / ItemKNN-k grid.
Trained models (BPR-MF, LightGCN, SimGCL): round-3 per-user files (all seeds), MostPop: round 3.
EASE / ItemKNN: round-4 cpu-gt kernels (extended grid, chosen on validation NDCG@20).
Round-3 per-user files store internal user ids (rank in sorted GT-train user set, run_v4.prep); they are mapped to raw ids
by re-running the same GT split. Check: round-3 MostPop per-user == round-4 MostPop per-user after mapping.
Test: best model by mean vs each other model, two-sided paired Wilcoxon (zero diffs dropped), Holm within dataset
(same as summarize_r3.py). Writes out/r4/gt_extgrid.md and out/r4/gt_extgrid.json."""
import os
ROOT = os.environ.get('GCF_ROOT', '.')  # project root containing exp/out/r2..r5 and paper/
import glob, json, re, numpy as np, pandas as pd
from scipy.stats import wilcoxon
E = os.path.join(ROOT, 'exp'); R3 = f'{E}/out/r3'; R4 = f'{E}/out/r4'
def load(name):
    if name == 'ml-1m':
        return pd.read_csv(f'{E}/data/ml-1m/ratings.dat', sep='::', engine='python', names=['u', 'i', 'r', 't']).drop(columns='r')
    return pd.read_csv(f'{E}/data/{name}.csv', usecols=['u', 'i', 't'])
def holm(ps):
    ps = np.asarray(ps, float); o = np.argsort(ps); m = len(ps); adj = np.empty(m); run = 0
    for r, i in enumerate(o): run = max(run, min(1, (m - r) * ps[i])); adj[i] = run
    return adj
LR = {'ml-1m': {'BPR-MF': '1e-3', 'LightGCN': '5e-3', 'SimGCL': '1e-3'}, 'gowalla': {'BPR-MF': '1e-3', 'LightGCN': '1e-3', 'SimGCL': '5e-3'},
      'amz-music': {'BPR-MF': '1e-3', 'LightGCN': '1e-3', 'SimGCL': '1e-3'}, 'amz-games': {'BPR-MF': '5e-3', 'LightGCN': '1e-3', 'SimGCL': '1e-3'}}
out, md = {}, ['# GT warm test set, extended EASE/ItemKNN grid (R4) + round-3 trained models', '',
               'Generated by exp/gt_extgrid_wilcoxon.py. Per-user NDCG@20; trained models averaged over their round-3 seeds.', '']
for ds in ['ml-1m', 'amz-games', 'amz-music', 'gowalla']:
    d = load(ds).sort_values('t', kind='stable'); n = len(d); tr = d.iloc[:int(.8 * n)]
    us = sorted(set(tr.u)); raw = np.array([str(u) for u in us])
    S = {}   # model -> seed -> {user: value}; deterministic models get seed 0 (= every seed)
    def r3(model, pat):
        fs = sorted(glob.glob(f'{R3}/gcf-r3-*/out_peruser_{ds}_global_temporal_s*_{pat}_global_temporal_{model}.npz'))
        S[model] = {}
        for f in fs:
            sd = int(re.search(r'_global_temporal_s(\d)_', f).group(1)); z = np.load(f)
            S[model][sd] = {raw[u]: float(v) for u, v in zip(z['users'], z['warm_NDCG@20']) if not np.isnan(v)}
        acc = {}
        for dd in S[model].values():
            for u, v in dd.items(): acc.setdefault(u, []).append(v)
        return {u: np.mean(v) for u, v in acc.items()}, len(fs)
    def r4(model):
        f = glob.glob(f'{R4}/gcf-r4-cpu-gt-{ds}/out_peruser_gtcpu_{ds}_s1_gt_{model}.npz')[0]; z = np.load(f)
        return {u: float(v) for u, v in zip(z['users_raw'], z['warm_NDCG@20']) if not np.isnan(v)}
    P, nseed = {}, {}
    P['MostPop'], _ = r3('MostPop', 'MostPop'); nseed['MostPop'] = 1
    mp4 = r4('MostPop'); common = set(mp4) & set(P['MostPop'])
    maxdiff = max(abs(mp4[u] - P['MostPop'][u]) for u in common)
    assert len(common) == len(mp4) == len(P['MostPop']) and maxdiff < 1e-6, (ds, len(common), len(mp4), len(P['MostPop']), maxdiff)
    for m in ['BPR-MF', 'LightGCN', 'SimGCL']: P[m], nseed[m] = r3(m, f'{m}_lr{LR[ds][m]}')
    P['ItemKNN'] = r4('ItemKNN'); P['EASE'] = r4('EASE'); nseed['ItemKNN'] = nseed['EASE'] = 1
    for m in ['MostPop', 'ItemKNN', 'EASE']: S[m] = {0: P[m]}
    def pair(a, b):   # per-user values averaged over the seeds both models have (summarize_r3.py convention)
        sa, sb = set(S[a]), set(S[b])
        if 0 in sa: sa = sb
        if 0 in sb: sb = sa
        cs = sorted(sa & sb); ga = lambda m, s: S[m][0] if 0 in S[m] else S[m][s]
        uu = sorted(set.intersection(*[set(ga(a, s)) & set(ga(b, s)) for s in cs]))
        return uu, np.array([np.mean([ga(a, s)[u] for s in cs]) - np.mean([ga(b, s)[u] for s in cs]) for u in uu])
    mean = {m: float(np.mean(list(v.values()))) for m, v in P.items()}
    best = max(mean, key=mean.get); rows = []
    for m in mean:
        if m == best: continue
        uu, x = pair(best, m); x = x[x != 0]
        rows.append([m, mean[best] - mean[m], len(uu), float(wilcoxon(x).pvalue)])
    adj = holm([r[3] for r in rows])
    # time-aware baselines (R4) vs the best of the six models; separate Holm family of two
    ta = []
    for m in ['RecentPop', 'EASE-TD']:
        P[m] = r4(m); S[m] = {0: P[m]}; mm = float(np.mean(list(P[m].values())))
        uu, x = pair(best, m); x = x[x != 0]; ta.append([m, mean[best] - mm, len(uu), float(wilcoxon(x).pvalue), mm])
    tadj = holm([r[3] for r in ta])
    out[ds] = dict(timeaware=[dict(vs=r[0], mean=r[4], diff=r[1], n=r[2], p_raw=r[3], p_holm=float(a)) for r, a in zip(ta, tadj)], mean=mean, n_seeds=nseed, best=best, n_users=len(P['MostPop']), mapping_check_maxdiff=maxdiff,
                   tests=[dict(vs=r[0], diff=r[1], n=r[2], p_raw=r[3], p_holm=float(a)) for r, a in zip(rows, adj)])
    md += [f'## {ds} (warm GT test users {len(P["MostPop"])}; mapping check max |ΔMostPop| = {maxdiff:.1e})', '',
           '| model | NDCG@20 | seeds |', '|---|---|---|'] + [f'| {m} | {mean[m]:.4f} | {nseed[m]} |' for m in sorted(mean, key=mean.get, reverse=True)]
    md += ['', f'best = {best}', '', '| vs | diff | n users | p raw | p Holm |', '|---|---|---|---|---|'] + \
          [f'| {r[0]} | {r[1]:+.5f} | {r[2]} | {r[3]:.3g} | {a:.3g} |' for r, a in zip(rows, adj)] + \
          ['', f'time-aware baselines vs {best} (own Holm family): ' + '; '.join(f'{r[0]} {r[4]:.4f} (diff {r[1]:+.5f}, p Holm {a:.3g})' for r, a in zip(ta, tadj)), '']
json.dump(out, open(f'{R4}/gt_extgrid.json', 'w'), indent=1); open(f'{R4}/gt_extgrid.md', 'w').write('\n'.join(md)); print('\n'.join(md))
